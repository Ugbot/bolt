TEST(ZstdParquet, GoldenZstdFileReadsWithExactValues) {
    using namespace bolt::ingest::parquet;
    std::vector<uint8_t> buf = slurp(data_path("golden_zstd.parquet"));
    ASSERT_FALSE(buf.empty()) << "golden_zstd.parquet missing";
    bolt::Arena arena;
    PqMeta* meta = static_cast<PqMeta*>(
        arena.allocate(sizeof(PqMeta), alignof(PqMeta)));
    ASSERT_NE(meta, nullptr);
    std::memset(meta, 0, sizeof(*meta));
    ASSERT_TRUE(parquet_read_meta(buf.data(), buf.size(), &arena, meta));
    ASSERT_EQ(meta->n_columns, 4u);
    ASSERT_EQ(meta->num_rows, 5000);
    ASSERT_GT(meta->n_row_groups, 1u);

    int64_t seen = 0;
    for (uint32_t g = 0; g < meta->n_row_groups; ++g) {
        bolt::BoltColumn cols[kPqMaxColumns];
        int64_t rows = 0;
        ASSERT_TRUE(parquet_read_row_group(buf.data(), buf.size(), meta, g,
                                           &arena, cols, &rows))
            << "row group " << g << " failed to decode -- this is exactly the "
               "pre-G2FEAT-134 behaviour (zstd pages were rejected)";
        ASSERT_GT(rows, 0);
        ASSERT_EQ(cols[0].type, bolt::BoltType::Int64);
        ASSERT_EQ(cols[1].type, bolt::BoltType::Int64);
        ASSERT_EQ(cols[2].type, bolt::BoltType::Float64);
        ASSERT_EQ(cols[3].type, bolt::BoltType::Utf8);
        const auto* id = static_cast<const int64_t*>(cols[0].data);
        const auto* v  = static_cast<const int64_t*>(cols[1].data);
        const auto* f  = static_cast<const double*>(cols[2].data);
        const auto* s  = static_cast<const bolt::StringView*>(cols[3].data);
        for (int64_t r = 0; r < rows; ++r) {
            const int64_t i = seen + r;
            EXPECT_EQ(id[r], i) << "row " << i;
            EXPECT_EQ(v[r], static_cast<int64_t>(
                          (static_cast<uint64_t>(i) * 2654435761ull) % 1000003ull))
                << "row " << i;
            EXPECT_DOUBLE_EQ(f[r], static_cast<double>(i) * 0.25) << "row " << i;
            char want[32];
            std::snprintf(want, sizeof(want), "row%05lld",
                          static_cast<long long>(i));
            const uint32_t wlen = static_cast<uint32_t>(std::strlen(want));
            ASSERT_EQ(s[r].length, wlen) << "row " << i;
            const char* got = (s[r].length <= 12u)
                ? &s[r].prefix[0]
                : static_cast<const char*>(cols[3].str_overflow_base) +
                      s[r].ref.offset;
            EXPECT_EQ(std::memcmp(got, want, wlen), 0) << "row " << i;
        }
        seen += rows;
    }
    EXPECT_EQ(seen, 5000);
}

TEST(ZstdParquet, ProjectionPushdownMatchesFullDecode) {
    using namespace bolt::ingest::parquet;
    std::vector<uint8_t> buf = slurp(data_path("golden_zstd.parquet"));
    ASSERT_FALSE(buf.empty());
    bolt::Arena arena;
    PqMeta* meta = static_cast<PqMeta*>(
        arena.allocate(sizeof(PqMeta), alignof(PqMeta)));
    ASSERT_NE(meta, nullptr);
    std::memset(meta, 0, sizeof(*meta));
    ASSERT_TRUE(parquet_read_meta(buf.data(), buf.size(), &arena, meta));
    for (uint32_t g = 0; g < meta->n_row_groups; ++g) {
        bolt::BoltColumn full[kPqMaxColumns];
        int64_t full_rows = 0;
        ASSERT_TRUE(parquet_read_row_group(buf.data(), buf.size(), meta, g,
                                           &arena, full, &full_rows));
        const uint16_t proj[2] = {2, 0};          // {f, id}, out of order
        bolt::BoltColumn cols[2];
        int64_t rows = 0;
        ASSERT_TRUE(parquet_read_row_group_cols(buf.data(), buf.size(), meta, g,
                                                proj, 2, &arena, cols, &rows));
        ASSERT_EQ(rows, full_rows);
        const auto* pf = static_cast<const double*>(cols[0].data);
        const auto* ff = static_cast<const double*>(full[2].data);
        const auto* pi = static_cast<const int64_t*>(cols[1].data);
        const auto* fi = static_cast<const int64_t*>(full[0].data);
        for (int64_t r = 0; r < rows; ++r) {
            EXPECT_DOUBLE_EQ(pf[r], ff[r]);
            EXPECT_EQ(pi[r], fi[r]);
        }
    }
}

