// G2FEAT-134 — bolt's self-contained Zstandard decoder, verified byte-exact
// against python-zstandard / pyarrow.
//
// WHY THIS EXISTS: zstd is pyiceberg's DEFAULT parquet codec, and bolt's
// parquet reader previously rejected it outright (PqCodec::Zstd fell into the
// `return false` arm), so the most common real Iceberg table on earth did not
// read. libzstd is optional and is not linked on a default build -- and is not
// installed on the dev box at all -- so the codec is owned, exactly as
// bolt_inflate.cpp owns DEFLATE rather than depending on zlib.
//
// THREE LAYERS OF VERIFICATION:
//   1. ZstdVectors     -- 33 reference frames from python-zstandard, decoded
//                         and compared BYTE FOR BYTE. Covers every block type
//                         (Raw/RLE/Compressed), every literal mode (Raw/RLE/
//                         Huffman 1- and 4-stream/Treeless) and every sequence
//                         mode (Predefined/RLE/FSE_Compressed/Repeat) that a
//                         real writer emits -- measured, not assumed. Six of
//                         the vectors are REAL parquet pages.
//   2. ZstdParquet     -- golden_zstd.parquet, a real pyarrow zstd file, read
//                         end to end through bolt's parquet reader with every
//                         value asserted. THIS TEST FAILS ON THE PRE-G2FEAT-134
//                         CODE BY CONSTRUCTION (the reader returned false).
//   3. ZstdMalformed   -- truncations, bit flips and random bytes must return
//                         an error code, never crash, never read/write out of
//                         bounds. (A dedicated ASAN mutation run covering ~93k
//                         malformed inputs was done during development; this
//                         keeps a bounded regression subset in CI.)
//
// Fixtures are regenerated by tests/data/make_zstd_vectors.py, which documents
// the deterministic patterns this file re-derives in `materialize()`.

