// 3. Malformed input: error code, never a crash or an OOB access
// ---------------------------------------------------------------------------
TEST(ZstdMalformed, TruncationsAndFlipsNeverCrash) {
    std::vector<Vector> vecs = load_vectors();
    ASSERT_FALSE(vecs.empty());
    Scratch sc;
    uint64_t rng = 0x9E3779B97F4A7C15ull;
    auto next = [&]() {
        rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; return rng;
    };
    long long ok = 0, err = 0;
    for (const Vector& v : vecs) {
        const size_t cap = static_cast<size_t>(v.raw_len) + 64;
        std::vector<uint8_t> out(cap);
        // truncations
        const size_t stride = v.comp.size() > 2048 ? v.comp.size() / 64 + 1 : 1;
        for (size_t len = 0; len < v.comp.size(); len += stride) {
            uint64_t n = 0;
            const int rc = zstd_decode_raw(v.comp.data(), len, out.data(),
                                           v.raw_len, &n,
                                           sc.ptr, zstd_scratch_size());
            (rc == kZstdOk) ? ++ok : ++err;
            if (rc == kZstdOk) EXPECT_LE(n, v.raw_len);
        }
        // bit flips
        for (int it = 0; it < 200; ++it) {
            if (v.comp.empty()) break;
            std::vector<uint8_t> bad = v.comp;
            const int nmut = 1 + static_cast<int>(next() % 3u);
            for (int m = 0; m < nmut; ++m) {
                bad[next() % bad.size()] ^= static_cast<uint8_t>(next() & 0xFFu);
            }
            uint64_t n = 0;
            const int rc = zstd_decode_raw(bad.data(), bad.size(), out.data(),
                                           v.raw_len, &n,
                                           sc.ptr, zstd_scratch_size());
            (rc == kZstdOk) ? ++ok : ++err;
            if (rc == kZstdOk) EXPECT_LE(n, v.raw_len);
        }
    }
    EXPECT_GT(err, 0);          // corruption must actually be detected
    SUCCEED() << ok << " decoded, " << err << " rejected; no crash";
}

TEST(ZstdMalformed, RandomBytesAreRejected) {
    Scratch sc;
    uint64_t rng = 0xDEADBEEFCAFEBABEull;
    auto next = [&]() {
        rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; return rng;
    };
    std::vector<uint8_t> out(8192);
    for (int it = 0; it < 4000; ++it) {
        const size_t len = static_cast<size_t>(next() % 512u) + 1u;
        std::vector<uint8_t> c(len);
        for (size_t i = 0; i < len; ++i) c[i] = static_cast<uint8_t>(next() & 0xFFu);
        if ((next() & 1u) && len >= 4) {          // half carry a valid magic
            c[0] = 0x28; c[1] = 0xB5; c[2] = 0x2F; c[3] = 0xFD;
        }
        uint64_t n = 0;
        const int rc = zstd_decode_raw(c.data(), c.size(), out.data(),
                                       out.size(), &n,
                                       sc.ptr, zstd_scratch_size());
        if (rc == kZstdOk) EXPECT_LE(n, out.size());
    }
    SUCCEED();
}

TEST(ZstdMalformed, NullAndZeroLengthAreHandled) {
    Scratch sc;
    uint64_t n = 12345;
    std::vector<uint8_t> out(64);
    EXPECT_EQ(zstd_decode_raw(nullptr, 0, out.data(), out.size(), &n,
                              sc.ptr, zstd_scratch_size()), kZstdTruncSrc);
    EXPECT_EQ(n, 0u);
    const uint8_t one = 0x28;
    EXPECT_NE(zstd_decode_raw(&one, 1, out.data(), out.size(), &n,
                              sc.ptr, zstd_scratch_size()), kZstdOk);
}

