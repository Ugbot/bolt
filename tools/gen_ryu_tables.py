"""Generate include/bolt/kernels/bolt_ryu_tables.h: Ryu's 128-bit powers of
five for shortest double -> decimal (Ulf Adams, PLDI 2018), from exact
integer arithmetic.

    python3 tools/gen_ryu_tables.py > include/bolt/kernels/bolt_ryu_tables.h

POW5_INV[q] = floor(2^(pow5bits(q) - 1 + 125) / 5^q) + 1, q in [0, 342)
POW5[i]     = 5^i scaled to exactly 125 bits (floor), i in [0, 326)
pow5bits(e) = bit length of 5^e (1 for e = 0).
"""

INV_BITS = 125
POW_BITS = 125
INV_N = 342
POW_N = 326


def pow5bits(e):
    return 1 if e == 0 else (5 ** e).bit_length()


def split(v):
    assert 0 <= v < 1 << 128
    return v & ((1 << 64) - 1), v >> 64


def main():
    out = ["// Generated by tools/gen_ryu_tables.py; do not edit.",
           "// Ryu (Ulf Adams, PLDI 2018) power-of-five tables, {low, high} 64-bit words.",
           "#pragma once", "", "#include <cstdint>", "",
           "namespace bolt {", "namespace kernels {", "namespace ryu {", "",
           "constexpr int32_t kPow5InvBitcount = %d;" % INV_BITS,
           "constexpr int32_t kPow5Bitcount = %d;" % POW_BITS,
           "constexpr uint32_t kPow5InvCount = %d;" % INV_N,
           "constexpr uint32_t kPow5Count = %d;" % POW_N, ""]
    out.append("alignas(64) inline constexpr uint64_t kPow5InvSplit[kPow5InvCount][2] = {")
    for q in range(INV_N):
        v = (1 << (pow5bits(q) - 1 + INV_BITS)) // 5 ** q + 1
        lo, hi = split(v)
        out.append("    {%du, %du}," % (lo, hi))
    out.append("};")
    out.append("")
    out.append("alignas(64) inline constexpr uint64_t kPow5Split[kPow5Count][2] = {")
    for i in range(POW_N):
        p = 5 ** i
        sh = pow5bits(i) - POW_BITS
        v = p >> sh if sh >= 0 else p << -sh
        lo, hi = split(v)
        out.append("    {%du, %du}," % (lo, hi))
    out.append("};")
    out += ["", "}  // namespace ryu", "}  // namespace kernels", "}  // namespace bolt", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
