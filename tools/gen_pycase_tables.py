"""Generate include/bolt/kernels/bolt_utf8_pycase_tables.h: Python's full case
mapping (str.lower / str.upper: SpecialCasing included) and the Final_Sigma
context classes, read from the running CPython's Unicode database.

    python3.13 tools/gen_pycase_tables.py > include/bolt/kernels/bolt_utf8_pycase_tables.h
"""
import sys
import unicodedata

SIGMA = "Σ"


def mapping(direction):
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = c.lower() if direction == "lower" else c.upper()
        if cp == 0x03A3 and direction == "lower":
            m = "σ"   # context handled by the kernel (Final_Sigma)
        if m != c:
            assert 1 <= len(m) <= 3, (hex(cp), m)
            out.append((cp, [ord(x) for x in m]))
    return out


def sigma_classes():
    ign, cased = [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or cp == 0x03A3:
            continue
        c = chr(cp)
        x = ("A" + c + SIGMA).lower()[-1] == "ς"
        y = (c + SIGMA).lower()[-1] == "ς"
        z = ("A" + SIGMA + c).lower()[1] == "ς"
        if x and z and not y:
            ign.append(cp)
        elif y:
            cased.append(cp)
    # Sigma itself is cased and not ignorable.
    cased.append(0x03A3)
    return ranges(ign), ranges(sorted(cased))


def ranges(cps):
    out = []
    for cp in cps:
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emit_map(name, rows):
    print("inline constexpr PyCaseMap %s[] = {" % name)
    for cp, m in rows:
        m = m + [0] * (3 - len(m))
        print("    {0x%05X, %d, {0x%05X, 0x%05X, 0x%05X}}," % (cp, len([x for x in m if x]) or 1, *m))
    print("};")


def emit_ranges(name, rows):
    print("inline constexpr PyCaseRange %s[] = {" % name)
    for lo, hi in rows:
        print("    {0x%05X, 0x%05X}," % (lo, hi))
    print("};")


def main():
    lower, upper = mapping("lower"), mapping("upper")
    ign, cased = sigma_classes()
    print("// GENERATED by tools/gen_pycase_tables.py from CPython %s, Unicode %s." % (
        sys.version.split()[0], unicodedata.unidata_version))
    print("// Python's str.lower / str.upper (full mapping, SpecialCasing) and the")
    print("// Final_Sigma context classes. Do not edit; regenerate.")
    print("#pragma once")
    print()
    print("#include <cstdint>")
    print()
    print("namespace bolt::kernels::utf8::pycase {")
    print()
    print('inline constexpr char kUnicodeVersion[] = "%s";' % unicodedata.unidata_version)
    print()
    print("struct PyCaseMap { uint32_t cp; uint32_t n; uint32_t m[3]; };")
    print("struct PyCaseRange { uint32_t lo; uint32_t hi; };")
    print()
    emit_map("kLower", lower)
    emit_map("kUpper", upper)
    space = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and chr(cp).isspace()]
    print("// str.strip() / split() whitespace: str.isspace()")
    print("inline constexpr uint32_t kSpace[] = {%s};" % ", ".join("0x%04X" % c for c in space))
    emit_ranges("kSigmaIgnorable", ign)
    emit_ranges("kSigmaCased", cased)
    print()
    print("}  // namespace bolt::kernels::utf8::pycase")


main()
